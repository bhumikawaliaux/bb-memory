export function personById(id, list = people) {
  return list.find((p) => p.id === id)
}

export function projectById(id, list = projects) {
  return list.find((p) => p.id === id)
}

export function memoryById(id, list) {
  return list.find((m) => m.id === id)
}

export function memoriesForPerson(id, list) {
  return list.filter((m) => m.people?.includes(id))
}

export function memoriesForProject(id, list) {
  return list.filter((m) => m.projectId === id)
}
